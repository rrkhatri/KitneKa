/**
 * Seed catalogue.
 *
 * Prices are AUTHORED, not random: each platform's price reflects a deliberate
 * market position (Zepto undercuts on staples, Amazon Fresh prices high on
 * branded lines, and so on) so the comparison screen demonstrates a real spread
 * rather than noise. This is a stand-in for a live feed — see
 * `src/lib/providers/remoteFeed.ts` for how a real feed replaces it.
 *
 * All money is in paise. Platform titles are written the way each platform
 * actually titles that product, because the matcher has to cope with that
 * variance and this data is what exercises it.
 */

import type { CanonicalProduct, PlatformId } from '@/lib/types';

export type SeedListing = {
  platform: PlatformId;
  title: string;
  mrpPaise: number;
  pricePaise: number;
  inStock: boolean;
  promoLabels: string[];
};

/** [platform, title, mrp₹, selling₹, inStock?, promo?] */
type Row = [
  PlatformId,
  string,
  number,
  number,
  boolean?,
  string?,
];

export type SeedProduct = CanonicalProduct & {
  listings: SeedListing[];
};

const rupees = (n: number) => Math.round(n * 100);

const DEFAULT_IMAGE = '/images/product-placeholder.svg';

function build(
  id: string,
  name: string,
  brand: string,
  category: string,
  packSize: string,
  unit: string,
  keywords: string[],
  rows: Row[],
): SeedProduct {
  return {
    id,
    name,
    brand,
    category,
    packSize,
    unit,
    imageUrl: DEFAULT_IMAGE,
    keywords,
    listings: rows.map(([platform, title, mrp, price, inStock = true, promo]) => ({
      platform,
      title,
      mrpPaise: rupees(mrp),
      pricePaise: rupees(price),
      inStock,
      promoLabels: promo ? [promo] : [],
    })),
  };
}

